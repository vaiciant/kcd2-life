"""Writes the list of factions of the people for reputation.lua (142 and 145).

They come from the civilians branch of FactionTree.xml, each parent before its children. It also writes the row
of the reputation panel of each one: itself if it has a UIName, and if not, the nearest one above.
And the parent of each one, because the panel of a faction instantly gets what moves above it.
It only needs to run if a game update changes the tree.

Usage: python -I -X utf8 mod/medieval_life/tools/generate_factions.py
"""
import pathlib
import xml.etree.ElementTree as ET

TABLE = pathlib.Path("game_files/Tables.pak/Libs/Tables/rpg/FactionTree.xml")
TARGET = pathlib.Path("mod/medieval_life/data/Scripts/MedievalLife/factions_data.lua")
ROOT_FACTION = "civilians"


def walk(node, row, parent, out):
    name = node.get("Name")
    row = name if node.get("UIName") else row
    out.append((name, row, parent))
    children = node.find("Children")
    for child in (children if children is not None else []):
        if child.tag == "Faction":
            walk(child, row, name, out)
    return out


def main():
    tree = ET.parse(TABLE).getroot().find("FactionTree")
    root = next(node for node in tree if node.get("Name") == ROOT_FACTION)
    factions = walk(root, None, None, [])
    names = "".join(f'\t"{name}",\n' for name, _, _ in factions)
    rows = "".join(f'\t["{name}"] = "{row}",\n' for name, row, _ in factions if row)
    parents = "".join(f'\t["{name}"] = "{parent}",\n' for name, _, parent in factions if parent)
    TARGET.write_text("-- Generated by tools/generate_factions.py from FactionTree.xml. Edit that script, not this file.\n"
                      "-- The factions of the people, each parent before its children.\n"
                      f"MedievalLife.FACTIONS = {{\n{names}}}\n"
                      "-- The row of the reputation panel that shows each faction: itself, or the nearest one above with a name.\n"
                      f"MedievalLife.FACTION_ROWS = {{\n{rows}}}\n"
                      "-- The parent of each one.\n"
                      f"MedievalLife.FACTION_PARENTS = {{\n{parents}}}\n", encoding="utf-8")
    print(f"{len(factions)} factions, {sum(1 for _, row, _ in factions if row)} with a panel row")


main()
